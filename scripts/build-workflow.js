#!/usr/bin/env node
'use strict';
// Builds n8n/workflow.json from the modules in src/, so the code that runs in n8n
// is the same code the unit tests cover. n8n Code nodes cannot require() local files,
// so each module is pasted into the node inside its own function scope.
//
//   node scripts/build-workflow.js          write n8n/workflow.json
//   node scripts/build-workflow.js --check  exit 1 if n8n/workflow.json is out of date

const fs = require('node:fs');
const path = require('node:path');
const { DEFAULT_CONFIG } = require('../src/config');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'n8n', 'workflow.json');

function inline(name, file) {
  const src = fs.readFileSync(path.join(ROOT, 'src', file), 'utf8').trim();
  return [
    `// ---- begin src/${file} (generated by scripts/build-workflow.js; edit the source file, not this node) ----`,
    `const ${name} = (() => {`,
    'const module = { exports: {} };',
    'const exports = module.exports;',
    src,
    'return module.exports;',
    '})();',
    `// ---- end src/${file} ----`,
  ].join('\n');
}

const CFG = "$('Config').first().json";
const MSG = "$('Parse event').first().json";
// The decision after the optional ticket step (only one of the two nodes runs per message).
const RESULT = "($('Ticket ref').isExecuted ? $('Ticket ref').first().json : $('Decide').first().json)";
const CHATWOOT_CONV = `={{ ${CFG}.chatwoot_url }}/api/v1/accounts/{{ ${MSG}.account_id }}/conversations/{{ ${MSG}.conversation_id }}`;

const cred = (name) => ({ httpHeaderAuth: { name } });

function code(name, x, jsCode) {
  return { parameters: { jsCode }, name, type: 'n8n-nodes-base.code', typeVersion: 2, position: [x[0], x[1]] };
}

function ifNode(name, pos, leftValue) {
  return {
    parameters: {
      conditions: {
        options: { caseSensitive: true, leftValue: '', typeValidation: 'loose', version: 2 },
        conditions: [{ id: `${name}-cond`, leftValue, rightValue: '', operator: { type: 'boolean', operation: 'true', singleValue: true } }],
        combinator: 'and',
      },
      options: {},
    },
    name,
    type: 'n8n-nodes-base.if',
    typeVersion: 2.2,
    position: pos,
  };
}

function httpPost(name, pos, url, jsonBody, credentialName, extra = {}) {
  const node = {
    parameters: {
      method: 'POST',
      url,
      authentication: 'genericCredentialType',
      genericAuthType: 'httpHeaderAuth',
      sendBody: true,
      specifyBody: 'json',
      jsonBody,
      options: { timeout: 20000 },
      ...(extra.parameters || {}),
    },
    name,
    type: 'n8n-nodes-base.httpRequest',
    typeVersion: 4.2,
    position: pos,
    credentials: cred(credentialName),
  };
  if (extra.onError) node.onError = extra.onError;
  return node;
}

const nodes = [
  {
    parameters: {
      content:
        '## AI chat to service ticket\n' +
        'Chatwoot Agent Bot webhook -> LLM (classify + extract) -> decision logic -> Odoo task -> reply / hand off.\n\n' +
        '1. Change the webhook path to a long random string.\n' +
        '2. Edit the **Config** node.\n' +
        '3. Create three Header Auth credentials: **LLM API key**, **Odoo API key**, **Chatwoot bot token** (see README).\n\n' +
        'Code nodes are generated from `src/` by `scripts/build-workflow.js`.',
      height: 300,
      width: 420,
    },
    name: 'About this workflow',
    type: 'n8n-nodes-base.stickyNote',
    typeVersion: 1,
    position: [-40, -380],
  },
  {
    parameters: { httpMethod: 'POST', path: 'chatwoot-bot/CHANGE-ME-to-a-long-random-string', responseMode: 'onReceived', options: {} },
    name: 'Chatwoot webhook',
    type: 'n8n-nodes-base.webhook',
    typeVersion: 2,
    position: [0, 0],
    webhookId: '6f1d2c3a-0b4e-4c8e-9a51-2f7e3d9b8c10',
  },
  code(
    'Config',
    [220, 0],
    '// Business facts and settings. Secrets do NOT go here; they live in n8n credentials.\n' +
      `return [{ json: ${JSON.stringify(DEFAULT_CONFIG, null, 2)} }];`
  ),
  code(
    'Parse event',
    [440, 0],
    `${inline('chatwoot', 'chatwoot.js')}\n\n` +
      "const e = chatwoot.parseEvent($('Chatwoot webhook').first().json);\n" +
      "if (e.kind === 'ignore') return []; // nothing to do: stop here\n" +
      'return [{ json: e }];'
  ),
  ifNode('Human took over?', [660, 0], "={{ $json.kind === 'release' }}"),
  httpPost('Chatwoot: release to humans', [880, -200], `${CHATWOOT_CONV}/toggle_status`, "={{ JSON.stringify({ status: 'open' }) }}", 'Chatwoot bot token'),
  code(
    'Build LLM request',
    [880, 100],
    `${inline('llm', 'llm.js')}\n\n` +
      `const e = ${MSG};\n` +
      `return [{ json: { body: llm.buildLlmRequest(${CFG}, e.text, e.state) } }];`
  ),
  httpPost(
    'LLM: classify and extract',
    [1100, 100],
    `={{ ${CFG}.llm_base_url }}/chat/completions`,
    '={{ JSON.stringify($json.body) }}',
    'LLM API key',
    { onError: 'continueRegularOutput' } // an LLM outage must not break the chat: Decide falls back to rules
  ),
  code(
    'Decide',
    [1320, 100],
    `${inline('llm', 'llm.js')}\n\n${inline('decision', 'decide.js')}\n\n` +
      `const e = ${MSG};\n` +
      'const llmResult = llm.parseLlmResponse($input.first().json);\n' +
      `const d = decision.decide({ message: e, state: e.state, llm: llmResult, config: ${CFG} });\n` +
      'return [{ json: { ...d, llm_ok: !!llmResult } }];'
  ),
  ifNode('Open a ticket?', [1540, 100], '={{ !!$json.ticket }}'),
  httpPost(
    'Odoo: create task',
    [1760, 0],
    `={{ ${CFG}.odoo_url }}/json/2/project.task/create`,
    `={{ JSON.stringify({ vals_list: [{ name: $json.ticket.name, description: $json.ticket.description, project_id: Number(${CFG}.odoo_project_id), priority: $json.ticket.priority }] }) }}`,
    'Odoo API key',
    {
      onError: 'continueRegularOutput', // a failed create is reported honestly by "Ticket ref"
      parameters: { sendHeaders: true, headerParameters: { parameters: [{ name: 'X-Odoo-Database', value: `={{ ${CFG}.odoo_db }}` }] } },
    }
  ),
  code(
    'Ticket ref',
    [1980, 0],
    `${inline('decision', 'decide.js')}\n\n` +
      '// Odoo returns [id]; depending on the n8n version the item is the number itself or wrapped.\n' +
      'const j = $input.first().json;\n' +
      "const id = (typeof j === 'number' || typeof j === 'string') ? j : Array.isArray(j) ? j[0] : (j && (j.data ?? j['0'] ?? j.id ?? j.result));\n" +
      "return [{ json: decision.applyTicketId($('Decide').first().json, Array.isArray(id) ? id[0] : id) }];"
  ),
  httpPost('Chatwoot: reply', [2200, 100], `${CHATWOOT_CONV}/messages`, "={{ JSON.stringify({ content: $json.reply, message_type: 'outgoing' }) }}", 'Chatwoot bot token'),
  httpPost(
    'Chatwoot: save state',
    [2420, 100],
    `${CHATWOOT_CONV}/custom_attributes`,
    `={{ JSON.stringify({ custom_attributes: { bot_state: JSON.stringify(${RESULT}.state) } }) }}`,
    'Chatwoot bot token'
  ),
  ifNode('Hand off?', [2640, 100], `={{ !!${RESULT}.handoff }}`),
  httpPost(
    'Chatwoot: note for staff',
    [2860, 0],
    `${CHATWOOT_CONV}/messages`,
    `={{ JSON.stringify({ content: ${RESULT}.handoff_note, message_type: 'outgoing', private: true }) }}`,
    'Chatwoot bot token'
  ),
  httpPost('Chatwoot: open for humans', [3080, 0], `${CHATWOOT_CONV}/toggle_status`, "={{ JSON.stringify({ status: 'open' }) }}", 'Chatwoot bot token'),
];

const link = (to) => [{ node: to, type: 'main', index: 0 }];
const connections = {
  'Chatwoot webhook': { main: [link('Config')] },
  Config: { main: [link('Parse event')] },
  'Parse event': { main: [link('Human took over?')] },
  'Human took over?': { main: [link('Chatwoot: release to humans'), link('Build LLM request')] },
  'Build LLM request': { main: [link('LLM: classify and extract')] },
  'LLM: classify and extract': { main: [link('Decide')] },
  Decide: { main: [link('Open a ticket?')] },
  'Open a ticket?': { main: [link('Odoo: create task'), link('Chatwoot: reply')] },
  'Odoo: create task': { main: [link('Ticket ref')] },
  'Ticket ref': { main: [link('Chatwoot: reply')] },
  'Chatwoot: reply': { main: [link('Chatwoot: save state')] },
  'Chatwoot: save state': { main: [link('Hand off?')] },
  'Hand off?': { main: [link('Chatwoot: note for staff')] },
  'Chatwoot: note for staff': { main: [link('Chatwoot: open for humans')] },
};

const workflow = {
  name: 'AI chat to service ticket',
  nodes,
  connections,
  active: false,
  settings: { executionOrder: 'v1', saveDataSuccessExecution: 'none' },
  pinData: {},
  meta: { templateCredsSetupCompleted: false },
  tags: [],
};

const text = JSON.stringify(workflow, null, 2) + '\n';

if (require.main === module) {
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== text) {
      console.error('n8n/workflow.json is out of date: run `node scripts/build-workflow.js`');
      process.exit(1);
    }
    console.log('n8n/workflow.json is up to date');
  } else {
    fs.writeFileSync(OUT, text);
    console.log(`wrote ${path.relative(ROOT, OUT)} (${nodes.length} nodes)`);
  }
}

module.exports = { workflow, text };
